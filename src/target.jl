const CUES = (:thorough, :always, :never)
const DEPLOYMENTS = (:spawn, :main)
const ERROR_MODES = (:stop, :continue, :null, :trim)

"""
    Target

A named unit of work: `f` is called with the values of the targets named in
`deps` (in order) and its result is cached. Build one with [`target`](@ref).
`group` is the template name of a target generated by [`tar_map`](@ref).
"""
struct Target
    name::Symbol
    f::Any
    deps::Vector{Symbol}
    format::Union{Symbol, StorageFormat}
    pattern::Union{Nothing, Symbol, Pattern}
    cue::Union{Symbol, CueRule}
    source::Union{Nothing, Expr}
    group::Union{Nothing, Symbol}
    seed::Union{Nothing, Symbol, Int}
    slots::Union{Symbol, Int}
    deployment::Symbol
    error::Symbol
    retries::Int
    retry_delay::Float64
end

"A copy of target `t` with some fields replaced."
with_fields(t::Target; changes...) = Target((
    get(changes, f, getfield(t, f))
    for f in fieldnames(Target)
)...)

"""
    target(name, f; deps = nothing, format = :jld2, pattern = nothing, cue = :thorough,
           seed = :auto, slots = 1, deployment = :spawn)

Declare a target. Unless `deps` is given, dependencies are the argument names
of `f`, which must therefore have exactly one method with positional arguments.

`format` is how the value is stored: `:jld2` (the default), `:jls`
(Serialization: fast, but tied to the Julia version), another format name made
available by a package extension, a [`StorageFormat`](@ref) value carrying
options, `:file` for a target that returns paths of files it reads or writes, or
`:url` for one that returns URLs whose changes (by HTTP `HEAD`) should rebuild
its consumers.

`seed` controls the random number generator `f` runs with: `:auto` seeds it
from the pipeline seed and the target's name (see [`tar_seed`](@ref)), an
integer pins the seed, and `nothing` leaves the session's generator alone.

`slots` and `deployment` matter for concurrent builds (`tar_make(; jobs)`).
`slots` is how many of the `jobs` the target occupies while it runs (an
integer, or `:all` to run with nothing else alongside); it controls what is
started next to the target, not how many threads the target itself uses
(see [`tar_slots`](@ref)). `deployment = :main` runs the target in the task that
called `tar_make`, never at the same time as another `:main` target, for code
that is not safe to run concurrently.

`error` says what a failure of this target does: `:stop` (the default) stops
the build unless `tar_make(; keep_going = true)`; `:continue` never stops it,
but blocks the target's descendants; `:null` gives consumers `nothing` so they
still run; `:trim` (branching targets) leaves failed branches out of the
target's value. In every mode the failed target is retried on the next build.

`retries` reruns a failing target up to that many more times within one build,
waiting `retry_delay` seconds between attempts, for flaky I/O. Every attempt
uses the same seed, so retrying a deterministic failure is pointless.
"""
function target(
    name::Symbol,
    # `f` is only stored and inspected, never called here. Each load of a
    # pipeline script makes new closures, so specializing on them would compile
    # this (and the helpers below) again for every target on every load. The
    # keyword body has too many arguments for Julia's rule against specializing
    # on uncalled functions to apply, hence the explicit `@nospecialize`.
    @nospecialize(f);
    deps::Union{Nothing, AbstractVector{Symbol}} = nothing,
    format::Union{Symbol, StorageFormat} = :jld2,
    pattern::Union{Nothing, Symbol, Pattern} = nothing,
    cue::Union{Symbol, CueRule} = :thorough,
    source::Union{Nothing, Expr} = nothing,
    seed::Union{Nothing, Symbol, Integer} = :auto,
    slots::Union{Symbol, Integer} = 1,
    deployment::Symbol = :spawn,
    error::Symbol = :stop,
    retries::Integer = 0,
    retry_delay::Real = 0,
)
    validate_name(name)
    format in (:file, :url) || resolve_format(format)
    (cue isa CueRule || cue in CUES) ||
        throw(ArgumentError(
            "target `$name`: cue must be one of $CUES or a cue value (cue_age, cue_force, Cue), got `$cue`",
        ))
    dependencies = deps === nothing ?
        arg_names(f, name) :
        check_explicit_deps(f, name, collect(deps))
    foreach(validate_name, dependencies)
    seed isa Symbol &&
        seed !== :auto &&
        throw(ArgumentError(
            "target `$name`: seed must be `:auto`, an integer or `nothing`, got `$seed`",
        ))
    seed_value = seed isa Integer ? Int(seed) : seed
    (slots === :all || (slots isa Integer && slots >= 1)) ||
        throw(ArgumentError(
            "target `$name`: slots must be a positive integer or `:all`, got `$slots`",
        ))
    error in ERROR_MODES ||
        throw(ArgumentError(
            "target `$name`: error must be one of $ERROR_MODES, got `$error`",
        ))
    (error === :trim && pattern === nothing) &&
        throw(ArgumentError("target `$name`: error = :trim needs a branching target"))
    (retries >= 0 && retry_delay >= 0) ||
        throw(ArgumentError("target `$name`: retries and retry_delay must not be negative"))
    deployment in DEPLOYMENTS ||
        throw(ArgumentError(
            "target `$name`: deployment must be one of $DEPLOYMENTS, got `$deployment`",
        ))
    return Target(
        name,
        f,
        dependencies,
        format,
        pattern,
        cue,
        source,
        nothing,
        seed_value,
        slots isa Integer ? Int(slots) : slots,
        deployment,
        error,
        Int(retries),
        Float64(retry_delay),
    )
end

function validate_name(name::Symbol)
    Base.isidentifier(name) ||
        throw(ArgumentError(
            "`$name` is not a valid target name: names must be valid Julia identifiers",
        ))
    return name
end

# The single place that touches the Base internal `method_argnames`.
_argnames(m::Method) = Symbol[Base.method_argnames(m)[2:end]...]

function single_method(@nospecialize(f), name::Symbol)
    ms = collect(methods(f))
    length(ms) == 1 && return only(ms)
    throw(ArgumentError(
        "target `$name`: its function has $(length(ms)) methods, so its dependencies cannot be inferred " *
            "from argument names. Wrap it in an anonymous function, e.g. `x -> f(x)`, or pass `deps = [...]`.",
    ))
end

"""
    arg_names(f, name = :target)

Names of the positional arguments of the single method of `f`.
"""
function arg_names(@nospecialize(f), name::Symbol = :target)
    m = single_method(f, name)
    m.isva &&
        throw(ArgumentError(
            "target `$name`: varargs functions need explicit `deps = [...]`",
        ))
    isempty(Base.kwarg_decl(m)) ||
        throw(ArgumentError(
            "target `$name`: keyword arguments are not supported; wrap the function in an anonymous function",
        ))
    args = _argnames(m)
    reserved = filter(a -> startswith(string(a), "_"), args)
    isempty(reserved) ||
        throw(ArgumentError(
            "target `$name`: argument names starting with `_` are reserved ($(join(reserved, ", ")))",
        ))
    return args
end

function check_explicit_deps(@nospecialize(f), name::Symbol, deps::Vector{Symbol})
    m = single_method(f, name)
    nargs = length(_argnames(m))
    ok = m.isva ? length(deps) >= nargs - 1 : length(deps) == nargs
    ok ||
        throw(ArgumentError(
            "target `$name`: its function takes $(m.isva ? "at least $(nargs - 1)" : nargs) " *
                "argument(s) but `deps` lists $(length(deps))",
        ))
    return deps
end

@testitem "target infers deps from argument names" begin
    using Targets: target, arg_names
    named(a, b) = a + b
    @test target(:x, named).deps == [:a, :b]
    @test target(:x, (clean, model) -> 1).deps == [:clean, :model]
    @test target(:x, () -> 1).deps == Symbol[]
    @test arg_names(() -> 1) == Symbol[]
end

@testitem "target accepts explicit deps" begin
    using Targets: target
    t = target(:all, (xs...) -> sum(xs); deps = [:a, :b, :c])
    @test t.deps == [:a, :b, :c]
    @test target(:y, (p, q) -> 1; deps = [:a, :b]).deps == [:a, :b]
    @test_throws ArgumentError target(:y, (p, q) -> 1; deps = [:a])
end

@testitem "target rejects unsupported functions" begin
    using Targets: target
    multi(a) = 1
    multi(a, b) = 2
    @test_throws "2 methods" target(:x, multi)
    @test_throws "varargs" target(:x, (a...) -> 1)
    kw(a; k = 1) = a
    @test_throws "keyword" target(:x, kw)
    @test_throws "reserved" target(:x, _a -> 1)
end

@testitem "target validates names and options" begin
    using Targets: target
    @test_throws "valid target name" target(Symbol("not valid"), () -> 1)
    @test_throws "valid target name" target(:x, a -> 1; deps = [Symbol("bad dep")])
    @test_throws ArgumentError target(:x, () -> 1; format = :no_such_format)
    @test_throws ArgumentError target(:x, () -> 1; cue = :sometimes)
    @test_throws "seed must be" target(:x, () -> 1; seed = :random)
    @test target(:x, () -> 1; seed = 3).seed == 3
    @test_throws "slots must be" target(:x, () -> 1; slots = 0)
    @test_throws "slots must be" target(:x, () -> 1; slots = :some)
    @test target(:x, () -> 1; slots = :all).slots === :all
    @test_throws "deployment must be" target(:x, () -> 1; deployment = :thread)
end
