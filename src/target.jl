const FORMATS = (:jld2, :file)
const CUES = (:thorough, :always, :never)

"""
    Target

A named unit of work: `f` is called with the values of the targets named in
`deps` (in order) and its result is cached. Build one with [`target`](@ref).
`group` is the template name of a target generated by [`tar_map`](@ref).
"""
struct Target
    name::Symbol
    f::Any
    deps::Vector{Symbol}
    format::Symbol
    pattern::Union{Nothing, Symbol}
    cue::Symbol
    source::Union{Nothing, Expr}
    group::Union{Nothing, Symbol}
end

"A copy of target `t` with some fields replaced."
with_fields(t::Target; changes...) = Target(
    (get(changes, f, getfield(t, f)) for f in fieldnames(Target))...,
)

"""
    target(name, f; deps = nothing, format = :jld2, pattern = nothing, cue = :thorough)

Declare a target. Unless `deps` is given, dependencies are the argument names
of `f`, which must therefore have exactly one method with positional arguments.
"""
function target(
    name::Symbol,
    f;
    deps::Union{Nothing, AbstractVector{Symbol}} = nothing,
    format::Symbol = :jld2,
    pattern::Union{Nothing, Symbol} = nothing,
    cue::Symbol = :thorough,
    source::Union{Nothing, Expr} = nothing,
)
    validate_name(name)
    format in FORMATS ||
        throw(ArgumentError(
            "target `$name`: format must be one of $FORMATS, got `$format`",
        ))
    cue in CUES ||
        throw(ArgumentError("target `$name`: cue must be one of $CUES, got `$cue`"))
    dependencies = deps === nothing ?
        arg_names(f, name) :
        check_explicit_deps(f, name, collect(deps))
    foreach(validate_name, dependencies)
    return Target(name, f, dependencies, format, pattern, cue, source, nothing)
end

function validate_name(name::Symbol)
    Base.isidentifier(name) ||
        throw(ArgumentError(
            "`$name` is not a valid target name: names must be valid Julia identifiers",
        ))
    return name
end

# The single place that touches the Base internal `method_argnames`.
_argnames(m::Method) = Symbol[Base.method_argnames(m)[2:end]...]

function single_method(f, name::Symbol)
    ms = collect(methods(f))
    length(ms) == 1 && return only(ms)
    throw(ArgumentError(
        "target `$name`: its function has $(length(ms)) methods, so its dependencies cannot be inferred " *
            "from argument names. Wrap it in an anonymous function, e.g. `x -> f(x)`, or pass `deps = [...]`.",
    ))
end

"""
    arg_names(f, name = :target)

Names of the positional arguments of the single method of `f`.
"""
function arg_names(f, name::Symbol = :target)
    m = single_method(f, name)
    m.isva &&
        throw(ArgumentError(
            "target `$name`: varargs functions need explicit `deps = [...]`",
        ))
    isempty(Base.kwarg_decl(m)) ||
        throw(ArgumentError(
            "target `$name`: keyword arguments are not supported; wrap the function in an anonymous function",
        ))
    args = _argnames(m)
    reserved = filter(a -> startswith(string(a), "_"), args)
    isempty(reserved) ||
        throw(ArgumentError(
            "target `$name`: argument names starting with `_` are reserved ($(join(reserved, ", ")))",
        ))
    return args
end

function check_explicit_deps(f, name::Symbol, deps::Vector{Symbol})
    m = single_method(f, name)
    nargs = length(_argnames(m))
    ok = m.isva ? length(deps) >= nargs - 1 : length(deps) == nargs
    ok ||
        throw(ArgumentError(
            "target `$name`: its function takes $(m.isva ? "at least $(nargs - 1)" : nargs) " *
                "argument(s) but `deps` lists $(length(deps))",
        ))
    return deps
end

@testitem "target infers deps from argument names" begin
    using Targets: target, arg_names
    named(a, b) = a + b
    @test target(:x, named).deps == [:a, :b]
    @test target(:x, (clean, model) -> 1).deps == [:clean, :model]
    @test target(:x, () -> 1).deps == Symbol[]
    @test arg_names(() -> 1) == Symbol[]
end

@testitem "target accepts explicit deps" begin
    using Targets: target
    t = target(:all, (xs...) -> sum(xs); deps = [:a, :b, :c])
    @test t.deps == [:a, :b, :c]
    @test target(:y, (p, q) -> 1; deps = [:a, :b]).deps == [:a, :b]
    @test_throws ArgumentError target(:y, (p, q) -> 1; deps = [:a])
end

@testitem "target rejects unsupported functions" begin
    using Targets: target
    multi(a) = 1
    multi(a, b) = 2
    @test_throws "2 methods" target(:x, multi)
    @test_throws "varargs" target(:x, (a...) -> 1)
    kw(a; k = 1) = a
    @test_throws "keyword" target(:x, kw)
    @test_throws "reserved" target(:x, _a -> 1)
end

@testitem "target validates names and options" begin
    using Targets: target
    @test_throws "valid target name" target(Symbol("not valid"), () -> 1)
    @test_throws "valid target name" target(:x, a -> 1; deps = [Symbol("bad dep")])
    @test_throws ArgumentError target(:x, () -> 1; format = :csv)
    @test_throws ArgumentError target(:x, () -> 1; cue = :sometimes)
end
